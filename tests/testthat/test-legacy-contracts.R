test_that("classical MDS reports rank and never takes negative square roots", {
  x <- rbind(c(0, 0), c(1, 0), c(0, 2), c(2, 3))
  X <- wrap.euclidean(x)
  out <- riem.mds(X, ndim = 3)
  expect_equal(as.matrix(dist(out$embed)), as.matrix(dist(x)), tolerance = 1e-10)
  expect_equal(out$effective_dimension, 2)
  expect_equal(out$embed[, 3], rep(0, 4))
  expect_lt(out$stress, 1e-10)
  constant <- riem.mds(wrap.euclidean(matrix(rep(1, 4), ncol = 1)), ndim = 2)
  expect_equal(constant$embed, matrix(0, 4, 2))
  expect_equal(constant$stress, 0)
  sphere <- wrap.sphere(rbind(c(1, 0), c(0, 1), c(-1, 0), c(0, -1)))
  curved <- riem.mds(sphere, ndim = 3)
  expect_true(length(curved$negative_eigenvalues) > 0)
  expect_true(all(is.finite(curved$embed)))
  expect_error(riem.mds(sphere, negative = "error"), "negative eigenvalue")
  expect_error(riem.mds(X, ndim = 4), "ndim")
})

test_that("kernel PCA uses sqrt eigenvalue scores in descending order", {
  x <- c(-1, 0, 1, 3)
  X <- wrap.euclidean(matrix(x, ncol = 1))
  sigma <- 1.2
  kernel <- exp(-outer(x, x, "-")^2 / (2 * sigma^2))
  H <- diag(4) - matrix(1 / 4, 4, 4)
  gram <- H %*% kernel %*% H
  out <- riem.kpca(X, ndim = 3, sigma = sigma)
  expect_equal(tcrossprod(out$embed), gram, tolerance = 1e-10)
  expect_equal(colSums(out$embed^2), out$vars[1:3], tolerance = 1e-10)
  expect_true(all(diff(out$vars) <= 0))
  expect_identical(out$kernel_status, "empirically_positive_semidefinite")
  expect_equal(dim(riem.kpca(X, ndim = 1)$embed), c(4L, 1L))
  expect_error(riem.kpca(X, sigma = 0), "positive")
  expect_error(riem.kpca(X, ndim = 4), "ndim")
  indefinite <- diag(c(1, 0.5, -0.2))
  expect_error(Riemann:::riem_legacy_eigen(indefinite, 2, "error"), "negative eigenvalue")
  truncated <- Riemann:::riem_legacy_eigen(indefinite, 2)
  expect_equal(truncated$negative_eigenvalues, -0.2)
})

test_that("Isomap uses mutual neighbors and exposes disconnected padding", {
  x <- c(0, 1, 3, 7)
  D <- abs(outer(x, x, "-"))
  graph <- Riemann:::riem_mutual_knn_graph(D, 1)
  expected <- matrix(FALSE, 4, 4)
  expected[1, 2] <- expected[2, 1] <- TRUE
  expect_identical(graph$adjacency, expected)
  expect_identical(graph$component, c(1L, 1L, 2L, 3L))
  X <- wrap.euclidean(matrix(x, ncol = 1))
  expect_error(riem.isomap(X, ndim = 1, nnbd = 1), "disconnected")
  expect_warning(out <- riem.isomap(X, ndim = 1, nnbd = 1, padding = TRUE), "artificial")
  expect_true(out$padded)
  expect_identical(out$adjacency, expected)
  complete <- riem.isomap(X, ndim = 1, nnbd = 3)
  expect_false(complete$padded)
  expect_equal(unname(as.matrix(dist(complete$embed))), D, tolerance = 1e-10)
  duplicated <- Riemann:::riem_mutual_knn_graph(abs(outer(c(0, 0, 1), c(0, 0, 1), "-")), 2)
  expect_true(duplicated$adjacency[1, 2])
  expect_equal(duplicated$distance[1, 2], 0)
})

reference_fanova_terms <- function(groups) {
  n <- sum(lengths(groups))
  proportions <- lengths(groups) / n
  all <- unlist(groups)
  squared <- lapply(groups, function(g) (g - mean(g))^2)
  v <- vapply(squared, mean, 0)
  s <- vapply(squared, function(z) mean(z^2) - mean(z)^2, 0)
  F <- mean((all - mean(all))^2) - sum(proportions * v)
  pairs <- combn(seq_along(groups), 2)
  U <- sum(apply(pairs, 2, function(ids) {
    prod(proportions[ids] / s[ids]) * diff(v[ids])^2
  }))
  c(variance = n * U / sum(proportions / s), mean = n * F^2 / sum(proportions^2 * s))
}

test_that("Frechet ANOVA matches equation14 with group proportions", {
  groups <- list(c(-1, 0, 2, 3), c(0, 1, 4, 8), c(-2, 1, 4, 7, 8))
  wrapped <- lapply(groups, function(x) wrap.euclidean(matrix(x, ncol = 1)))
  out <- do.call(riem.fanova, wrapped)
  reference <- reference_fanova_terms(groups)
  expect_equal(out$terms, reference, tolerance = 1e-10)
  expect_equal(unname(out$statistic), sum(reference), tolerance = 1e-10)
  expect_equal(out$p.value, pchisq(sum(reference), df = 2, lower.tail = FALSE), tolerance = 1e-10)
  expect_equal(out$group_proportions, lengths(groups) / sum(lengths(groups)))
  expect_identical(out$calibration, "asymptotic_chisquared")
  scaled <- lapply(groups, function(x) wrap.euclidean(matrix(x * 1e100, ncol = 1)))
  expect_equal(do.call(riem.fanova, scaled)$statistic, out$statistic, tolerance = 1e-10)
  expect_error(riem.fanova(wrapped[[1]]), "at least two groups")
  expect_error(riem.fanova(wrapped[[1]], wrap.euclidean(list(1, 2))), "three")
  constant <- wrap.euclidean(as.list(rep(1, 4)))
  expect_error(riem.fanova(constant, constant), "degenerate")
})

test_that("ANOVA permutations refit groups and use inclusive Monte Carlo p-values", {
  X <- wrap.euclidean(as.list(c(-1, 0, 2, 3)))
  Y <- wrap.euclidean(as.list(c(0, 1, 4, 8)))
  set.seed(17)
  first <- riem.fanovaP(X, Y, nperm = 19)
  set.seed(17)
  second <- riem.fanovaP(X, Y, nperm = 19)
  expect_equal(first$permutation_statistics, second$permutation_statistics)
  expect_equal(first$p.value, (1 + sum(first$permutation_statistics >= first$statistic)) / 20)
  expect_equal(length(first$permutation_statistics), 19)
  expect_identical(first$calibration, "random_label_permutation")
  expect_error(riem.fanovaP(X, Y, nperm = 0), "nperm")
})

