test_that("distance-summary permutation testing validates its actual contract", {
  X <- wrap.euclidean(as.list(c(0, 1, 2)))
  Y <- wrap.euclidean(as.list(c(3, 5, 7, 10)))
  dx <- mean(dist(c(0, 1, 2)))
  dy <- mean(dist(c(3, 5, 7, 10)))
  dxy <- mean(abs(outer(c(0, 1, 2), c(3, 5, 7, 10), "-")))
  set.seed(103)
  out <- riem.test2bg14(X, Y, nperm = 9)
  expect_equal(unname(out$statistic), (dx - dxy)^2 + (dy - dxy)^2)
  expect_equal(out$p.value, (1 + sum(out$permutation_statistics >= out$statistic)) / 10)
  expect_gte(out$p.value, 0.1)
  expect_error(riem.test2bg14(X, wrap.euclidean(list(1))), "two observations")
  expect_error(riem.test2bg14(X, Y, nperm = 0), "nperm")
  identical_data <- wrap.euclidean(as.list(rep(1, 3)))
  expect_equal(riem.test2bg14(identical_data, identical_data, nperm = 3)$p.value, 1)
})

test_that("transport validates probability mass and singleton costs", {
  X <- wrap.euclidean(as.list(c(0, 2)))
  Y <- wrap.euclidean(as.list(c(1, 5)))
  out <- riem.wasserstein(X, Y, p = 2)
  expect_equal(out$distance, sqrt(5), tolerance = 1e-10)
  expect_equal(rowSums(out$plan), c(0.5, 0.5))
  expect_equal(colSums(out$plan), c(0.5, 0.5))
  expect_identical(out$geometry$geometry_id, "euclidean")
  singleton <- riem.wasserstein(wrap.euclidean(list(0)), Y, p = 2,
                                weight2 = c(1e308, 1e308))
  expect_equal(singleton$distance, sqrt(13), tolerance = 1e-10)
  expect_equal(dim(singleton$plan), c(1L, 2L))
  expect_error(riem.wasserstein(X, Y, p = 0.5), "at least one")
  expect_error(riem.wasserstein(X, Y, weight1 = c(0, 0)), "positive")
  expect_error(riem.wasserstein(X, Y, weight1 = c(NA, 1)), "finite")
  expect_error(riem.wasserstein(X, wrap.sphere(list(c(1, 0)))), "manifold")
  set.seed(9)
  perm <- riem.test2wass(wrap.euclidean(list(0)), Y, nperm = 9)
  expect_equal(perm$statistic, c(Wmn = sqrt(13)), tolerance = 1e-10)
  expect_equal(perm$p.value, (1 + sum(perm$permutation_statistics >= perm$statistic)) / 10)
  expect_identical(perm$solver, "linear_program")
  expect_error(riem.test2wass(X, Y, nperm = 0), "nperm")
})

test_that("angular densities declare uniform probability measure and stable scaling", {
  theta <- seq(0, 2 * pi, length.out = 20001)[-20001]
  X <- cbind(cos(theta), sin(theta))
  A <- diag(c(4, 1))
  density <- dacg(X, A)
  expect_equal(mean(density), 1, tolerance = 1e-9)
  expect_equal(dacg(X[1:5, ], diag(2)), rep(1, 5), tolerance = 1e-12)
  expected <- det(A)^(-0.5) * rowSums((X[1:5, ] %*% solve(A)) * X[1:5, ])^(-1)
  expect_equal(density[1:5], expected, tolerance = 1e-12)
  expect_equal(dacg(X[1:5, ], A * 1e-250), density[1:5], tolerance = 1e-12)
  expect_equal(dacg(-X[1:5, ], A), density[1:5], tolerance = 1e-12)
  expect_equal(dacg(X[1:5, ], A, log = TRUE), log(density[1:5]), tolerance = 1e-12)
  bases <- lapply(1:5, function(i) matrix(X[i, ], ncol = 1))
  expect_equal(dmacg(bases, A), density[1:5], tolerance = 1e-12)
  expect_equal(dmacg(bases, A * 1e250, log = TRUE), log(density[1:5]), tolerance = 1e-12)
  expect_error(dmacg(bases, diag(3)), "row dimension")
  Q <- qr.Q(qr(matrix(c(1, 0, 2, 0, 1, 1), 3, 2)))
  expect_equal(dmacg(list(Q), diag(3)), 1, tolerance = 1e-12)
  S <- diag(c(2, 3, 1))
  expect_equal(dmacg(list(Q), S), dmacg(list(Q %*% matrix(c(0, 1, 1, 0), 2)), S),
               tolerance = 1e-12)
})

test_that("angular sampling and fitting retain their statistical contracts", {
  set.seed(90)
  vectors <- racg(6, diag(c(2, 1, 3)))
  expect_equal(vapply(vectors, function(x) sum(x^2), 0), rep(1, 6), tolerance = 1e-12)
  set.seed(90)
  expect_equal(racg(6, diag(c(2, 1, 3))), vectors)
  expect_error(racg(0, diag(3)), "n")
  expect_error(racg(2.5, diag(3)), "n")
  bases <- rmacg(1, 2, diag(3))
  expect_equal(dim(bases[[1]]), c(3L, 2L))
  expect_equal(crossprod(bases[[1]]), diag(2), tolerance = 1e-12)
  expect_error(rmacg(2.5, 1, diag(3)), "n")
  expect_error(rmacg(1, 4, diag(3)), "r")
  angles <- c(0, 0.21, 0.77, 1.23, 1.71, 2.23, 2.66, 3.09)
  x <- cbind(cos(angles), sin(angles))
  fit <- mle.acg(x, maxiter = 200, eps = 1e-10)
  expect_true(attr(fit, "converged"))
  expect_equal(sum(diag(fit)), 2, tolerance = 1e-12)
  q <- rowSums((x %*% solve(fit)) * x)
  fixed <- crossprod(x / sqrt(q))
  fixed <- fixed * 2 / sum(diag(fixed))
  expect_equal(unname(as.vector(fit)), as.vector(fixed), tolerance = 1e-9)
  expect_equal(attr(fit, "objective"), -mean(dacg(x, fit, log = TRUE)), tolerance = 1e-12)
  expect_warning(limited <- mle.acg(x, maxiter = 1), "did not converge")
  expect_false(attr(limited, "converged"))
  expect_error(mle.acg(matrix(rep(c(1, 0), 3), ncol = 2, byrow = TRUE)), "span")
  expect_error(mle.macg(list(diag(2), diag(2))), "not identifiable")
  expect_error(mle.acg(x, eps = 0), "positive")
})

